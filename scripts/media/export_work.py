"""Exports the approved work photos for the site and writes src/config/work-images.ts.

    python -P scripts/media/export_work.py <frames_dir> <manifest.csv>

Reads design/work/work.json (frame number, id, category, alt, optional crop), takes each frame
from <frames_dir>, removes letterbox bars and the listed crop, and saves
public/images/work/<id>.webp at its own size (never upscaled, at most 1600 px wide).
Run `npm run images` afterwards to make the smaller copies.
"""
import csv
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
MAX_WIDTH = 1600


def content_box(image: Image.Image) -> tuple[int, int, int, int]:
    gray = np.asarray(image.convert("L"), dtype=np.float32)
    rows = np.where(gray.mean(axis=1) > 18)[0]
    cols = np.where(gray.mean(axis=0) > 18)[0]
    if len(rows) == 0 or len(cols) == 0:
        return 0, 0, image.width, image.height
    top, bottom, left, right = rows[0], rows[-1] + 1, cols[0], cols[-1] + 1
    trimmed = top > 4 or bottom < image.height - 4 or left > 4 or right < image.width - 4
    inset = 0.02 if trimmed else 0
    dy, dx = int((bottom - top) * inset), int((right - left) * inset)
    return left + dx, top + dy, right - dx, bottom - dy


def main(frames_dir: Path, manifest_file: Path) -> None:
    spec = json.loads((ROOT / "design/work/work.json").read_text(encoding="utf-8"))
    frames = {int(r["n"]): r for r in csv.DictReader(open(frames_dir / "candidates.csv", encoding="utf-8"))}
    videos = {r["video_id"]: r for r in csv.DictReader(open(manifest_file, encoding="utf-8"))}
    out_dir = ROOT / "public/images/work"
    out_dir.mkdir(parents=True, exist_ok=True)
    entries = []

    for item in spec:
        frame = frames[item["n"]]
        image = Image.open(frame["path"]).convert("RGB")
        image = image.crop(content_box(image))
        crop = item.get("crop", {})
        w, h = image.size
        image = image.crop((
            int(w * crop.get("left", 0)), int(h * crop.get("top", 0)),
            int(w * (1 - crop.get("right", 0))), int(h * (1 - crop.get("bottom", 0))),
        ))
        if image.width > MAX_WIDTH:
            image = image.resize((MAX_WIDTH, round(image.height * MAX_WIDTH / image.width)), Image.LANCZOS)
        image.save(out_dir / f"{item['id']}.webp", quality=82, method=6)

        video = videos[frame["video_id"]]
        entries.append({
            "id": item["id"],
            "src": f"/images/work/{item['id']}.webp",
            "width": image.width,
            "height": image.height,
            "alt": item["alt"],
            "category": item["category"],
            **({"pair": item["pair"], "stage": item["stage"]} if "pair" in item else {}),
            "source": {"video": video["url"], "time": round(float(frame["time_s"]), 1)},
        })

    lines = [
        "// Generated by scripts/media/export_work.py from design/work/work.json. Edit the JSON and run it again.",
        "// Frames from the client's TikTok videos; `source` points to the video and second each one came from.",
        "import type { WorkImage } from './work';",
        "",
        "export const workImages: WorkImage[] = [",
    ]
    for entry in entries:
        lines.append(f"  {json.dumps(entry, ensure_ascii=False)},")
    lines.append("];")
    (ROOT / "src/config/work-images.ts").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Exported {len(entries)} images to {out_dir}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
